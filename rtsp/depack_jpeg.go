package rtsp

import "time"

var jpegEOI = []byte{0xFF, 0xD9}

// jpegDepacketizer rebuilds JPEG images from RFC 2435 payloads.
type jpegDepacketizer struct {
	t       *track
	b       unitBuilder
	active  bool
	bad     bool
	ts      uint32
	next    int
	tables  [128]byte
	nTables int
}

func (d *jpegDepacketizer) reset() { d.active, d.bad = false, false; d.b.discard() }
func (d *jpegDepacketizer) lost()  { d.bad = d.active }

func (d *jpegDepacketizer) push(h rtpHeader, p []byte, arrival time.Time) {
	if d.active && h.ts != d.ts {
		d.active = false
		d.b.discard()
		d.t.dropUnit()
	}
	if len(p) < 8 {
		d.bad = d.active
		return
	}
	offset := int(p[1])<<16 | int(p[2])<<8 | int(p[3])
	typ, q, w, ht := p[4], p[5], int(p[6])*8, int(p[7])*8
	p = p[8:]
	restart := -1
	if typ >= 64 && typ < 128 {
		if len(p) < 4 {
			d.bad = d.active
			return
		}
		restart = int(p[0])<<8 | int(p[1])
		p = p[4:]
		typ -= 64
	}
	if offset == 0 {
		if d.active {
			d.t.dropUnit()
		}
		d.active, d.bad = false, false
		if q >= 128 {
			if len(p) < 4 {
				d.t.dropUnit()
				return
			}
			n := int(p[2])<<8 | int(p[3])
			if p[1] != 0 || n > len(p)-4 || (n != 0 && n != 64 && n != 128) {
				d.t.dropUnit()
				return
			}
			if n > 0 {
				copy(d.tables[:], p[4:4+n])
				d.nTables = n / 64
			}
			p = p[4+n:]
			if d.nTables == 0 {
				d.t.dropUnit()
				return
			}
		} else {
			if q == 0 {
				d.t.dropUnit()
				return
			}
			jpegQuantTables(int(q), &d.tables)
			d.nTables = 2
		}
		if typ > 1 || w == 0 || ht == 0 {
			d.t.dropUnit()
			return
		}
		d.b.begin(0)
		if !d.writeHeader(int(typ), w, ht, restart) {
			d.b.discard()
			d.t.dropUnit()
			return
		}
		d.active, d.ts, d.next = true, h.ts, 0
		if d.t.info.Width != w || d.t.info.Height != ht {
			d.t.setSize(w, ht)
		}
	}
	if !d.active {
		return
	}
	if offset != d.next {
		d.bad = true
	}
	if !d.bad {
		if !d.b.write(p) {
			d.bad = true
		}
		d.next += len(p)
	}
	if !h.marker {
		return
	}
	d.active = false
	if d.bad || !d.b.write(jpegEOI) {
		d.b.discard()
		d.t.dropUnit()
		return
	}
	d.t.emit(d.b.take(), h.ts, true, arrival)
}

func (d *jpegDepacketizer) writeHeader(typ, w, h, restart int) bool {
	if !d.b.room(1024) {
		return false
	}
	out := d.b.p.store[d.b.end:d.b.end]
	out = append(out, 0xFF, 0xD8)
	n := d.nTables
	for i := 0; i < 2; i++ {
		tbl := min(i, n-1)
		out = append(out, 0xFF, 0xDB, 0, 67, byte(i))
		out = append(out, d.tables[tbl*64:tbl*64+64]...)
	}
	if restart > 0 {
		out = append(out, 0xFF, 0xDD, 0, 4, byte(restart>>8), byte(restart))
	}
	sampling := byte(0x21)
	if typ == 1 {
		sampling = 0x22
	}
	out = append(out, 0xFF, 0xC0, 0, 17, 8, byte(h>>8), byte(h), byte(w>>8), byte(w), 3,
		1, sampling, 0, 2, 0x11, 1, 3, 0x11, 1)
	out = appendHuffman(out, 0x00, lumDCCounts[:], dcSymbols[:])
	out = appendHuffman(out, 0x10, lumACCounts[:], lumACSymbols[:])
	out = appendHuffman(out, 0x01, chmDCCounts[:], dcSymbols[:])
	out = appendHuffman(out, 0x11, chmACCounts[:], chmACSymbols[:])
	out = append(out, 0xFF, 0xDA, 0, 12, 3, 1, 0x00, 2, 0x11, 3, 0x11, 0, 63, 0)
	d.b.end += len(out)
	return true
}

func appendHuffman(out []byte, class byte, counts, symbols []byte) []byte {
	n := 3 + len(counts) + len(symbols)
	out = append(out, 0xFF, 0xC4, byte(n>>8), byte(n), class)
	out = append(out, counts...)
	return append(out, symbols...)
}

// jpegQuantTables fills dst with the two RFC 2435 tables for quality q, in the
// zigzag order that DQT uses.
func jpegQuantTables(q int, dst *[128]byte) {
	s := 200 - 2*q
	if q < 50 {
		s = 5000 / q
	}
	for i, z := range jpegZigzag {
		dst[i] = scaleQuant(int(jpegLuma[z]), s)
		dst[64+i] = scaleQuant(int(jpegChroma[z]), s)
	}
}

func scaleQuant(v, s int) byte { return byte(min(max((v*s+50)/100, 1), 255)) }

